// Extracts the real T-Rex from Chromium's open-source offline sprite sheet and
// writes it out as a pixel map, so the artwork is the actual game asset rather
// than something traced by eye. Four hand-drawn attempts got the proportions
// wrong; this cannot.
//
// Usage: node scripts/extract-dino-sprite.mjs
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { chromium } from "playwright-core";
import { root } from "./lib/local-browser.mjs";

const SHEET =
  "https://raw.githubusercontent.com/chromium/chromium/main/components/neterror/resources/images/default_100_percent/offline/100-offline-sprite.png";
const CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
// Frame offsets from offline.js's 1x sprite definitions.
const FRAMES = {
  dino: { x: 848, y: 2, w: 44, h: 47 },
  cactusSmall: { x: 228, y: 2, w: 17, h: 35 },
};

const cachePath = resolve(root, "scripts/lib/offline-sprite.png");
let png;
try {
  png = await readFile(cachePath);
} catch {
  const response = await fetch(SHEET);
  if (!response.ok) throw new Error(`sprite download failed: ${response.status}`);
  png = Buffer.from(await response.arrayBuffer());
  await writeFile(cachePath, png);
  console.log("downloaded sprite sheet");
}
const dataUri = `data:image/png;base64,${png.toString("base64")}`;

const browser = await chromium.launch({ executablePath: CHROME });
try {
  const page = await browser.newPage();
  await page.setContent("<body></body>");
  const maps = await page.evaluate(
    async ({ uri, frames }) => {
      const img = new Image();
      img.src = uri;
      await img.decode();
      const canvas = document.createElement("canvas");
      canvas.width = img.width;
      canvas.height = img.height;
      const ctx = canvas.getContext("2d");
      ctx.drawImage(img, 0, 0);
      const out = {};
      for (const [name, f] of Object.entries(frames)) {
        const data = ctx.getImageData(f.x, f.y, f.w, f.h).data;
        const rows = [];
        for (let y = 0; y < f.h; y++) {
          let row = "";
          for (let x = 0; x < f.w; x++) {
            const i = (y * f.w + x) * 4;
            // The sheet is dark ink on transparent; treat any inked pixel as on.
            row += data[i + 3] > 40 && data[i] < 200 ? "#" : ".";
          }
          rows.push(row);
        }
        // Trim fully empty edge rows so the sprite sits flush.
        while (rows.length && !rows[0].includes("#")) rows.shift();
        while (rows.length && !rows[rows.length - 1].includes("#")) rows.pop();
        out[name] = rows;
      }
      return out;
    },
    { uri: dataUri, frames: FRAMES },
  );

  const body = Object.entries(maps)
    .map(
      ([name, rows]) =>
        `export const ${name.toUpperCase()} = [\n${rows.map((r) => `  "${r}",`).join("\n")}\n];`,
    )
    .join("\n\n");

  await writeFile(
    resolve(root, "scripts/lib/dino-sprites.mjs"),
    `// GENERATED by scripts/extract-dino-sprite.mjs from Chromium's offline\n` +
      `// sprite sheet (BSD-licensed). Do not hand-edit — re-run the extractor.\n\n` +
      `${body}\n`,
  );
  for (const [name, rows] of Object.entries(maps)) {
    console.log(`${name}: ${rows[0]?.length ?? 0}x${rows.length}`);
  }
} finally {
  await browser.close();
}
